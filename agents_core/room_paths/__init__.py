# ---------------------------------------------------------------------------
# Shell emitter
# ---------------------------------------------------------------------------

def _emit_sh() -> str:
    lines = [
        "# Generated by: python -m agents_core.room_paths --emit-sh",
        "# DO NOT EDIT — source of truth is agents_core/room_paths/_classmap.toml",
        "",
        f'export ROOM_ROOT="{_ROOT_DEFAULT}"',
        "",
    ]
    for key, entry in _KEYS.items():
        sh_name = "ROOM_" + key.upper().replace(".", "_")
        default_path = Path(_ROOT_DEFAULT) / entry["subpath"]
        lines.append(f'export {sh_name}="{default_path}"')
    lines.append("")
    return "\n".join(lines)


def _emit_rust() -> str:
    lines = [
        "// Generated by: python -m agents_core.room_paths --emit-rust",
        "// DO NOT EDIT — source of truth is agents_core/room_paths/_classmap.toml",
        "",
        f'pub const ROOM_ROOT: &str = "{_ROOT_DEFAULT}";',
        "",
    ]
    for key, entry in _KEYS.items():
        rust_name = "ROOM_" + key.upper().replace(".", "_").replace("-", "_")
        default_path = Path(_ROOT_DEFAULT) / entry["subpath"]
        lines.append(f'pub const {rust_name}: &str = "{default_path}";')
    return "\n".join(lines)
